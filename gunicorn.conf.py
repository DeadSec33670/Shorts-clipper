"""Настройки боевого сервера. Запуск:  gunicorn -c gunicorn.conf.py web:app

ВАЖНО про количество процессов.
Пока обработка живёт в памяти веб-процесса (глобальный _state в web.py),
воркер должен быть РОВНО ОДИН: при двух и более пользователь будет попадать
то в один процесс, то в другой, и увидит «обработка не запущена» сразу после
запуска. Несколько воркеров можно будет включить только после Этапа 2
(вынос задач в очередь Redis + общее хранилище состояния).
"""
import multiprocessing  # noqa: F401  — понадобится после Этапа 2

import os

# Адрес прослушивания.
# В контейнере слушать 127.0.0.1 нельзя: этот адрес виден только внутри
# контейнера, и снаружи сайт не откроется. Поэтому в Docker слушаем 0.0.0.0,
# а наружу порт всё равно не публикуется — доступ идёт через nginx.
# При запуске на голой машине остаётся 127.0.0.1: там 0.0.0.0 означал бы,
# что gunicorn доступен из интернета в обход nginx.
bind = os.environ.get("CLIPPER_BIND") or (
    "0.0.0.0:8000" if os.path.exists("/.dockerenv") else "127.0.0.1:8000")
workers = 1                  # см. пояснение выше — не увеличивать до Этапа 2
threads = 8                  # хватает на SSE-подписчиков и параллельные запросы
worker_class = "gthread"

# Обработка видео идёт десятки минут, а лог отдаётся потоком (SSE).
# Со стандартным таймаутом 30 с gunicorn убивал бы такие соединения.
timeout = 3600
graceful_timeout = 60
keepalive = 65               # чуть больше, чем keepalive у nginx

max_requests = 1000          # мягкий перезапуск: страхует от утечек памяти
max_requests_jitter = 100

accesslog = "-"              # в stdout — дальше их подхватит systemd/docker
errorlog = "-"
loglevel = "info"
# %({X-Forwarded-For}i)s — реальный IP клиента, а не адрес nginx
access_log_format = ('%({X-Forwarded-For}i)s %(t)s "%(r)s" %(s)s %(b)s %(D)sмкс')

forwarded_allow_ips = "127.0.0.1"   # доверяем заголовкам только от своего nginx
proc_name = "shorts-clipper"
